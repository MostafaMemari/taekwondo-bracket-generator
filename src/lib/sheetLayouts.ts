/**
 * طرح برگه — سه چیدمان متفاوت برای «همان» برگه قرعه:
 *
 *  - کلاسیک: سربرگ سه ستونه با خط زیر سربرگ، ردیف ها با نوار رنگی کنار،
 *    اتصال های پیوسته — همان ظاهر همیشگی که پیش فرض است.
 *  - مدرن: ریبون رنگی لبه بالای برگه، لوگوی کاشی دار، عنوان با خط تزئینی دو
 *    طرف، بج های پیل، آمار به شکل پیل های عمودی، ردیف ها با نوار رنگی لبه
 *    بالا، اتصال های خط چین و پلاک قهرمان کپسولی.
 *  - تشریفاتی: حال و هوای سند قهرمانی — قاب دو خطه با نشان الماسی چهار گوشه
 *    دور تمام صفحه، سربرگ مرکزی با جداکننده الماسی دار و بج های مدالی دورخط،
 *    آمار در یک خط با جداکننده الماسی، ردیف ها با دورخط داخلی هم رنگ گوشه،
 *    اتصال های مهره ای (نقطه های گرد) و پلاک قهرمان با الماس های دو طرف.
 *
 * طرح «ساختار» است و تم «رنگ» — هر تمی (هفت تم فعلی و تم های آینده) روی هر
 * سه طرح یک جا می نشیند؛ مدرن و تشریفاتی همه رنگ هایشان را از همان توکن های
 * تم می گیرند تا تم سیاه و سفید هم رویشان بی عیب چاپ شود. تیتر دورها (یک
 * چهارم/نیمه نهایی/فینال) در هر سه طرح متن ساده و بی کادر است — قانون ثابت
 * بازخورد کاربر.
 */
export type SheetLayoutId = 'classic' | 'modern' | 'royal'

export interface SheetLayoutInfo {
  id: SheetLayoutId
  /** نام فارسی طرح — در تنظیمات */
  name: string
  /** توضیح یک خطی زیر نام در تنظیمات */
  hint: string
}

export const sheetLayouts: readonly SheetLayoutInfo[] = [
  {
    id: 'classic',
    name: 'کلاسیک',
    hint: 'همان سربرگ و جدول همیشگی — نوار گوشه کنار ردیف ها',
  },
  {
    id: 'modern',
    name: 'مدرن',
    hint: 'ریبون رنگی بالا، بج های پیل، نوار گوشه روی ردیف ها',
  },
  {
    id: 'royal',
    name: 'تشریفاتی',
    hint: 'قاب دو خطه با نشان الماسی، بج های مدالی و اتصال مهره ای — شکوه قهرمانی',
  },
]

const layoutIds: ReadonlySet<string> = new Set(sheetLayouts.map((layout) => layout.id))

export function isSheetLayoutId(value: unknown): value is SheetLayoutId {
  return typeof value === 'string' && layoutIds.has(value)
}

/** طرح معتبر از store — مقدار نامعتبر/قدیمی بی درنگ کلاسیک می شود */
export function normalizeSheetLayoutId(value: unknown): SheetLayoutId {
  return isSheetLayoutId(value) ? value : 'classic'
}
